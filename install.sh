#!/usr/bin/env bash
# Deploy this repo onto the current machine. Idempotent; safe to re-run.
#
#   ./install.sh <host>        host = a file name in shell/hosts/ without its extension
#
# Writes stubs for ~/.zshrc or ~/.bashrc and ~/.gitconfig that point into the repo, and
# symlinks the tmux and herdr configs. Anything it replaces is kept as <file>.pre-profile.<stamp>.
set -euo pipefail

PROFILE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HOST="${1:-}"
STAMP="$(date +%Y%m%d%H%M%S)"
MARKER="# Generated by profile/install.sh — edit $PROFILE_DIR, not this file"

usage() {
    echo "Usage: $0 <host>"
    echo "Hosts: $(ls "$PROFILE_DIR/shell/hosts" | sed 's/\.[a-z]*$//' | tr '\n' ' ')"
    exit 1
}

[ -n "$HOST" ] || usage
if [ -f "$PROFILE_DIR/shell/hosts/$HOST.zsh" ]; then
    RC="$HOME/.zshrc"
    ENTRY="shell/zsh/init.zsh"
elif [ -f "$PROFILE_DIR/shell/hosts/$HOST.bash" ]; then
    RC="$HOME/.bashrc"
    ENTRY="shell/bash/init.bash"
else
    usage
fi

backup() {
    mv "$1" "$1.pre-profile.$STAMP"
    echo "    [i] Backed up $1 -> $1.pre-profile.$STAMP"
}

line_count() {
    printf '%s\n' "$1" | awk 'END { print NR }'
}

# write_stub <file> <content> <what trailing lines mean>
# A file that already starts with exactly <content> is left alone. Lines after the stub are
# reported rather than removed: tool installers append to ~/.zshrc, and ~/.gitconfig keeps
# machine-local settings (credential helpers) there on purpose.
write_stub() {
    local file="$1" content="$2" trailing="$3" lines extra
    lines="$(line_count "$content")"
    if [ -f "$file" ] && [ "$(head -n "$lines" "$file")" = "$content" ]; then
        extra="$(tail -n +"$((lines + 1))" "$file" | grep -v '^[[:space:]]*$' || true)"
        if [ -n "$extra" ]; then
            echo "    [!] $file has $(line_count "$extra") line(s) after the stub ($trailing):"
            printf '%s\n' "$extra" | sed 's/^/        /'
        else
            echo "    [-] $file already up to date."
        fi
        return 1
    fi
    if [ -e "$file" ] || [ -L "$file" ]; then
        backup "$file"
    fi
    printf '%s\n' "$content" > "$file"
    echo "    [✓] Wrote $file"
}

# link <repo path> <target in $HOME>
link() {
    local src="$PROFILE_DIR/$1" dest="$2"
    if [ -L "$dest" ] && [ "$(readlink "$dest")" = "$src" ]; then
        echo "    [-] $dest already links to the repo."
        return 0
    fi
    mkdir -p "$(dirname "$dest")"
    if [ -e "$dest" ] || [ -L "$dest" ]; then
        backup "$dest"
    fi
    ln -s "$src" "$dest"
    echo "    [✓] Linked $dest -> $src"
}

echo "--> Shell ($HOST)"
write_stub "$RC" "$MARKER
export PROFILE_DIR=\"$PROFILE_DIR\"
export PROFILE_HOST=\"$HOST\"
source \"\$PROFILE_DIR/$ENTRY\"" "move them into the repo" || true

GIT_HOST_CONFIG="$PROFILE_DIR/config/git/hosts/$HOST.gitconfig"
if [ -f "$GIT_HOST_CONFIG" ]; then
    echo "--> Git"
    GITCONFIG="$HOME/.gitconfig"
    if write_stub "$GITCONFIG" "$MARKER
[include]
	path = $GIT_HOST_CONFIG" "machine-local settings"; then
        # A fresh stub replaced a hand-maintained file. Carry over every key the repo doesn't
        # define (credential helpers, signing keys, ...) so nothing is silently dropped.
        OLD_GITCONFIG="$GITCONFIG.pre-profile.$STAMP"
        if [ -f "$OLD_GITCONFIG" ]; then
            REPO_KEYS="$(git config --file "$GIT_HOST_CONFIG" --list --name-only | sort -u)"
            git config --file "$OLD_GITCONFIG" --list --name-only | sort -u | while read -r key; do
                if ! printf '%s\n' "$REPO_KEYS" | grep -qxF "$key"; then
                    git config --file "$OLD_GITCONFIG" --get-all "$key" | while read -r value; do
                        git config --file "$GITCONFIG" --add "$key" "$value"
                    done
                    echo "    [i] Kept local key from the old ~/.gitconfig: $key"
                fi
            done
        fi
    fi
fi

if [ "$HOST" != "win-vdi" ]; then
    if command -v tmux &> /dev/null; then
        echo "--> tmux"
        link config/tmux/tmux.conf "$HOME/.tmux.conf"
    fi
    if command -v herdr &> /dev/null; then
        echo "--> herdr"
        link config/herdr/config.toml "$HOME/.config/herdr/config.toml"
    fi
fi

echo "Done. Open a new shell, or run: source $RC"
